logger = logging.getLogger("sap_bridge.primitives.joints_write")


def _resolve_name(state: Any, name: str | None, existing: set[str], consume: bool) -> str:
    """Resolve the final joint name under the hybrid-naming rule.

    Explicit name → prefix-enforced + conflict-checked. Omitted → autogen (peek if not
    consuming, e.g. a dry-run preview; consume on a real create). Autogen also conflict-checks
    (defensive: a manual AI_J005 could collide with the counter)."""
    if name is not None:
        assert_prefix_required(name)
        assert_no_conflict(name, list(existing))
        return name
    auto = next_joint_name(state) if consume else peek_joint_name(state)
    assert_no_conflict(auto, list(existing))
    return auto


def _add_joint(sap_model: Any, x: float, y: float, z: float, name: str) -> str:
    """AddCartesian with Name="" + UserName=name → SAP names the point `name`. Read back (M2)."""
    ret = sap_model.PointObj.AddCartesian(x, y, z, "", name, "Global")
    ret_code = ret[0] if isinstance(ret, tuple) else ret
    if ret_code != 0:
        raise SapSessionError(
            error_codes.OAPI_CALL_FAILED,
            f"PointObj.AddCartesian('{name}') returned {ret_code}",
        )
    # SAP returns the assigned name as the out-param; trust it but it should equal `name`.
    assigned = ret[1] if isinstance(ret, tuple) and len(ret) > 1 and ret[1] else name
    return str(assigned)


def create_joint(
    sap_model: Any, state: Any, x: float, y: float, z: float,
    name: str | None, dry_run: bool, confirm: bool,
) -> CreateJointResponse:
    """Create one joint at (x,y,z). Hybrid naming; confirm mandatory (modifies the model)."""
    with audited("create_joint", {"x": x, "y": y, "z": z, "name": name,
                                  "dry_run": dry_run, "confirm": confirm}) as ctx:
        existing = set(joints_read.list_joint_names(sap_model))

        if dry_run:
            final = _resolve_name(state, name, existing, consume=False)
            ctx["result"] = "preview_only"
            ctx["result_details"] = {"name": final, "coords": [x, y, z]}
            return CreateJointResponse(
                dry_run=True, would_apply=JointCreated(name=final, x=x, y=y, z=z)
            )

        if not confirm:
            raise SapSessionError(
                error_codes.CONFIRM_REQUIRED,
                "create_joint modifies the model; pass confirm=true to create",
            )

        final = _resolve_name(state, name, existing, consume=True)
        assigned = _add_joint(sap_model, x, y, z, final)
        ctx["result_details"] = {"name": assigned, "coords": [x, y, z]}
        return CreateJointResponse(
            dry_run=False, applied=JointCreated(name=assigned, x=x, y=y, z=z)
        )


def create_joints(
    sap_model: Any, state: Any, joints: list[dict], dry_run: bool, confirm: bool,
) -> CreateJointsResponse:
    """Create many joints atomically (stop-on-first-failure). Autogen names resolve in order so
    the preview shows exactly what a real run would assign."""
    with audited("create_joints", {"count": len(joints), "dry_run": dry_run, "confirm": confirm}) as ctx:
        if not joints:
            raise SapSessionError(error_codes.EMPTY_BATCH, "create_joints: the batch is empty")

        # Resolve every name up front against a GROWING set (so two autogens / two explicit
        # names in the same batch don't collide). This is the strict pre-validation step.
        existing = set(joints_read.list_joint_names(sap_model))
        resolved: list[JointCreated] = []
        for spec in joints:
            final = _resolve_name(state, spec.get("name"), existing, consume=not dry_run)
            existing.add(final)
            resolved.append(JointCreated(name=final, x=spec["x"], y=spec["y"], z=spec["z"]))

        if dry_run:
            ctx["result"] = "preview_only"
            ctx["result_details"] = {"count": len(resolved)}
            return CreateJointsResponse(
                dry_run=True, count=len(resolved), would_apply=resolved
            )

        if not confirm:
            raise SapSessionError(
                error_codes.CONFIRM_REQUIRED,
                f"create_joints creates {len(joints)} joint(s); pass confirm=true to apply",
            )

        def _apply(_idx: int, jc: JointCreated) -> JointCreated:
            self_name = _add_joint(sap_model, jc.x, jc.y, jc.z, jc.name)
            return JointCreated(name=self_name, x=jc.x, y=jc.y, z=jc.z)

        outcome = apply_batch_atomic(resolved, _apply)
        failed = None
        not_attempted = None
        if outcome.failed_index is not None:
            fi = outcome.failed_item
            from ..contracts import BatchItemFailure
            failed = BatchItemFailure(
                index=outcome.failed_index,
                item=f"joint '{fi.name}' at ({fi.x},{fi.y},{fi.z})",
                reason=outcome.failed_reason or "unknown",
            )
            not_attempted = [j.name for j in outcome.not_attempted]
        ctx["result"] = "applied" if failed is None else f"error_{error_codes.OAPI_CALL_FAILED}"
        ctx["result_details"] = {"applied_count": len(outcome.applied),
                                 "failed_at": failed.index if failed else None}
        return CreateJointsResponse(
            dry_run=False, count=len(resolved), applied=outcome.applied,
            failed_at=failed, not_attempted=not_attempted,
        )


def delete_joint(
    sap_model: Any, name: str, dry_run: bool, confirm: bool,
) -> DeleteJointResponse:
    """Delete a joint. Refuses (joint_has_connected_frames) if any frame touches it — the
    client deletes those frames first (no automatic cascade, decisión #5). confirm mandatory."""
    with audited("delete_joint", {"name": name, "dry_run": dry_run, "confirm": confirm}) as ctx:
        if name not in set(joints_read.list_joint_names(sap_model)):
            raise SapSessionError(
                error_codes.OBJECT_NOT_FOUND, f"joint '{name}' not found"
            )
        connected = get_frames_connected_to_joint(sap_model, name)

        if dry_run:
            ctx["result"] = "preview_only"
            ctx["result_details"] = {"name": name, "connected_frames": connected}
            return DeleteJointResponse(
                dry_run=True,
                would_apply=JointDeletion(name=name, connected_frames=connected),
            )

        if connected:
            raise SapSessionError(
                error_codes.JOINT_HAS_CONNECTED_FRAMES,
                f"cannot delete joint '{name}': it has connected frames {connected}. "
                "Delete those frames first (no automatic cascade).",
            )
        if not confirm:
            raise SapSessionError(
                error_codes.CONFIRM_REQUIRED,
                f"delete_joint removes joint '{name}'; pass confirm=true to delete",
            )

        from ..sap_session import get_session
        item_objects = get_session().oapi_namespace().eItemType.Objects
        ret = sap_model.PointObj.DeleteSpecialPoint(name, item_objects)
        ret_code = ret[0] if isinstance(ret, tuple) else ret
        if ret_code != 0:
            raise SapSessionError(
                error_codes.OAPI_CALL_FAILED,
                f"PointObj.DeleteSpecialPoint('{name}') returned {ret_code}",
            )
        ctx["result_details"] = {"name": name}
        return DeleteJointResponse(
            dry_run=False, applied=JointDeletion(name=name, connected_frames=[])
        )


def modify_joint(
    sap_model: Any, name: str, x: float, y: float, z: float, dry_run: bool, confirm: bool,
) -> ModifyJointResponse:
    """Move a joint to new coords. Affects every connected frame → confirm mandatory; the
    preview lists the affected frames."""
    with audited("modify_joint", {"name": name, "x": x, "y": y, "z": z,
                                  "dry_run": dry_run, "confirm": confirm}) as ctx:
        if name not in set(joints_read.list_joint_names(sap_model)):
            raise SapSessionError(error_codes.OBJECT_NOT_FOUND, f"joint '{name}' not found")
        old = list(joints_read.get_joint_coords(sap_model, name))
        affected = get_frames_connected_to_joint(sap_model, name)

        if dry_run:
            ctx["result"] = "preview_only"
            ctx["result_details"] = {"name": name, "old": old, "new": [x, y, z],
                                     "affected_frames": affected}
            return ModifyJointResponse(
                dry_run=True,
                would_apply=JointMove(name=name, previous_coords=old, new_coords=[x, y, z],
                                      affected_frames=affected),
            )

        if not confirm:
            raise SapSessionError(
                error_codes.CONFIRM_REQUIRED,
                f"modify_joint moves '{name}' and affects {len(affected)} connected frame(s); "
                "pass confirm=true to apply",
            )

        ret = sap_model.EditPoint.ChangeCoordinates_1(name, x, y, z, False)
        ret_code = ret[0] if isinstance(ret, tuple) else ret
        if ret_code != 0:
            raise SapSessionError(
                error_codes.OAPI_CALL_FAILED,
                f"EditPoint.ChangeCoordinates_1('{name}') returned {ret_code}",
            )
        now = list(joints_read.get_joint_coords(sap_model, name))  # read back (M2)
        ctx["result_details"] = {"name": name, "previous": old, "current": now}
        return ModifyJointResponse(
            dry_run=False,
            applied=JointMove(name=name, previous_coords=old, current_coords=now,
                              affected_frames=affected),
        )


# --- Joint restraints (Fase 1h.3) --------------------------------------------
# SAP DOF order [U1,U2,U3,R1,R2,R3] (§34). The contract uses named flags; here we map to/from
# the positional 6-bool array SetRestraint/GetRestraint want.
_DOF_ORDER = ("U1", "U2", "U3", "R1", "R2", "R3")


def _restraints_to_list(flags: RestraintFlags) -> list[bool]:
    return [getattr(flags, dof) for dof in _DOF_ORDER]


def _list_to_restraints(values: Any) -> RestraintFlags:
    return RestraintFlags(**{dof: bool(values[i]) for i, dof in enumerate(_DOF_ORDER)})


def _diff_restraints(prev: RestraintFlags, new: RestraintFlags) -> list[str]:
    return [f"{dof}: {getattr(prev, dof)} → {getattr(new, dof)}"
            for dof in _DOF_ORDER if getattr(prev, dof) != getattr(new, dof)]


def _apply_restraints(sap_model: Any, oapi_namespace: Any, name: str, new: RestraintFlags) -> RestraintFlags:
    """SetRestraint then read back (M2). SetRestraint overwrites the whole state (§34)."""
    item_objects = oapi_namespace.eItemType.Objects
    ret = sap_model.PointObj.SetRestraint(name, _restraints_to_list(new), item_objects)
    ret_code = ret[0] if isinstance(ret, tuple) else ret
    if ret_code != 0:
        raise SapSessionError(
            error_codes.OAPI_CALL_FAILED,
            f"PointObj.SetRestraint('{name}') returned {ret_code}",
        )
    return _list_to_restraints(joints_read.get_joint_restraints(sap_model, name))


def set_joint_restraints(
    sap_model: Any, oapi_namespace: Any, name: str, restraints: dict, dry_run: bool, confirm: bool,
) -> SetJointRestraintsResponse:
    """Set a joint's 6-DOF restraints. Named flags (omitted = False); SetRestraint OVERWRITES the
    whole state (M1, §34). confirm mandatory."""
    with audited("set_joint_restraints", {"name": name, "restraints": restraints,
                                          "dry_run": dry_run, "confirm": confirm}) as ctx:
        if name not in set(joints_read.list_joint_names(sap_model)):
            raise SapSessionError(error_codes.OBJECT_NOT_FOUND, f"joint '{name}' not found")
        new = RestraintFlags(**restraints)
        prev = _list_to_restraints(joints_read.get_joint_restraints(sap_model, name))
        changes = _diff_restraints(prev, new)

        if dry_run:
            ctx["result"] = "preview_only"
            ctx["result_details"] = {"name": name, "changes": changes}
            return SetJointRestraintsResponse(
                dry_run=True,
                would_apply=JointRestraintsChange(name=name, previous=prev, new=new, changes=changes),
            )

        if not confirm:
            raise SapSessionError(
                error_codes.CONFIRM_REQUIRED,
                f"set_joint_restraints modifies joint '{name}'; pass confirm=true to apply",
            )

        cur = _apply_restraints(sap_model, oapi_namespace, name, new)
        ctx["result_details"] = {"name": name, "changes": changes}
        return SetJointRestraintsResponse(
            dry_run=False,
            applied=JointRestraintsChange(name=name, previous=prev, current=cur, changes=changes),
        )


def set_joint_restraints_batch(
    sap_model: Any, oapi_namespace: Any, items: list[dict], dry_run: bool, confirm: bool,
) -> SetJointRestraintsBatchResponse:
    """Set restraints on many joints atomically (stop-on-first-failure)."""
    with audited("set_joint_restraints_batch",
                 {"count": len(items), "dry_run": dry_run, "confirm": confirm}) as ctx:
        if not items:
            raise SapSessionError(error_codes.EMPTY_BATCH, "set_joint_restraints_batch: empty")

        # Strict pre-validation: every joint must exist; resolve change records.
        existing = set(joints_read.list_joint_names(sap_model))
        records: list[JointRestraintsChange] = []
        for spec in items:
            jname = spec["name"]
            if jname not in existing:
                raise SapSessionError(error_codes.OBJECT_NOT_FOUND, f"joint '{jname}' not found")
            new = RestraintFlags(**spec["restraints"])
            prev = _list_to_restraints(joints_read.get_joint_restraints(sap_model, jname))
            records.append(JointRestraintsChange(
                name=jname, previous=prev, new=new, changes=_diff_restraints(prev, new)))

        if dry_run:
            ctx["result"] = "preview_only"
            ctx["result_details"] = {"count": len(records)}
            return SetJointRestraintsBatchResponse(
                dry_run=True, count=len(records), would_apply=records)

        if not confirm:
            raise SapSessionError(
                error_codes.CONFIRM_REQUIRED,
                f"set_joint_restraints_batch modifies {len(items)} joint(s); pass confirm=true",
            )

        def _apply(_idx: int, rec: JointRestraintsChange) -> JointRestraintsChange:
            cur = _apply_restraints(sap_model, oapi_namespace, rec.name, rec.new)
            return JointRestraintsChange(name=rec.name, previous=rec.previous, current=cur,
                                         changes=rec.changes)

        outcome = apply_batch_atomic(records, _apply)
        failed = None
        not_attempted = None
        if outcome.failed_index is not None:
            rec = outcome.failed_item
            failed = BatchItemFailure(index=outcome.failed_index,
                                      item=f"joint '{rec.name}'",
                                      reason=outcome.failed_reason or "unknown")
            not_attempted = [r.name for r in outcome.not_attempted]
        ctx["result"] = "applied" if failed is None else f"error_{error_codes.OAPI_CALL_FAILED}"
        ctx["result_details"] = {"applied_count": len(outcome.applied),
                                 "failed_at": failed.index if failed else None}
        return SetJointRestraintsBatchResponse(
            dry_run=False, count=len(records), applied=outcome.applied,
            failed_at=failed, not_attempted=not_attempted)
