"""Write-side joint (point) primitives: create / create batch / delete / modify (Fase 1h.2).

Hybrid naming (write_side_design §3e): an explicit name is prefix-enforced (§1); an omitted
name is autogenerated AI_J### off the session counter (peek for previews, consume on apply).

OAPI notes (brechas §32, §33, verified in pre-flight):
  * PointObj.AddCartesian(X, Y, Z, Name="", UserName, "Global") → (0, name). With Name="" SAP
    uses UserName as the point name. Requires a buildable model (NewBlank, §32).
  * A joint is deleted with PointObj.DeleteSpecialPoint(Name, eItemType) — cPointObj has NO
    .Delete (§33). SAP only deletes points with no connected objects, so delete_joint refuses
    a joint that still has frames (connection check) before calling it.
  * A joint is moved with EditPoint.ChangeCoordinates_1(Name, X, Y, Z, NoRefresh).
"""
from __future__ import annotations

import logging
from typing import Any

from .. import error_codes
from ..audit_log import audited
from ..bridge_state import next_joint_name, peek_joint_name
from ..contracts import (
    BatchItemFailure,
    CreateJointResponse,
    CreateJointsResponse,
    DeleteJointResponse,
    JointCreated,
    JointDeletion,
    JointMove,
    JointRestraintsChange,
    ModifyJointResponse,
    RestraintFlags,
    SetJointRestraintsBatchResponse,
    SetJointRestraintsResponse,
)
from ..namespace import assert_no_conflict, assert_prefix_required
from ..sap_session import SapSessionError
from . import joints as joints_read
